import fs from 'node:fs';
import path from 'node:path';
import type { BuildMode, Note } from '../types.js';
import { includeNote, redactText } from './privacy.js';
import { chunkNote } from './chunks.js';

function esc(s: string) {
  return s.replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!);
}

export function assertSafeOutputDir(out: string) {
  const resolved = path.resolve(out);
  const cwd = path.resolve(process.cwd());
  const home = process.env.HOME ? path.resolve(process.env.HOME) : undefined;
  const forbidden = new Set([path.parse(resolved).root, cwd]);
  if (home) forbidden.add(home);
  if (forbidden.has(resolved)) {
    throw new Error(`Refusing to delete unsafe output directory: ${resolved}`);
  }
  if (!path.relative(cwd, resolved) || path.relative(cwd, resolved).startsWith('..')) {
    // Allow explicit absolute temp/build paths, but reject parent dirs of cwd that
    // are commonly reached by typos like --out ..
    const rel = path.relative(resolved, cwd);
    if (rel && !rel.startsWith('..')) throw new Error(`Refusing to delete parent directory of current project: ${resolved}`);
  }
  return resolved;
}

function safeNoteForMode(note: Note, mode: BuildMode): Note {
  if (mode !== 'redacted') return note;
  return {
    ...note,
    body: redactText(note.body),
    html: redactText(note.html),
    text: redactText(note.text),
    meta: Object.fromEntries(Object.entries(note.meta).map(([k, v]) => [k, typeof v === 'string' ? redactText(v) : v])),
  };
}

function page(title: string, main: string) {
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${esc(title)}</title><link rel="stylesheet" href="../assets/style.css"><meta name="generator" content="agent-memory-site"></head><body><header data-index="false"><nav><a href="../index.html">Dashboard</a> <a href="../search-index.json">Search JSON</a> <a href="../manifest.json">Manifest</a></nav></header><main>${main}</main><footer data-index="false">Generated by Agent Memory Site</footer></body></html>`;
}

function rootPage(title: string, main: string) {
  return page(title, main).replaceAll('../assets/style.css', 'assets/style.css').replaceAll('../index.html', 'index.html').replaceAll('../search-index.json', 'search-index.json').replaceAll('../manifest.json', 'manifest.json');
}

export function buildSite(notes: Note[], out: string, mode: BuildMode) {
  const safeOut = assertSafeOutputDir(out);
  fs.rmSync(safeOut, { recursive: true, force: true });
  fs.mkdirSync(path.join(safeOut, 'notes'), { recursive: true });
  fs.mkdirSync(path.join(safeOut, 'assets'), { recursive: true });
  const visible = notes.filter((n) => includeNote(n, mode)).map((n) => safeNoteForMode(n, mode));
  const byCat = groupBy(visible, (n: Note) => n.category);
  for (const n of visible) {
    const body = n.html;
    const backlinks = n.backlinks
      .filter((id) => visible.some((v) => v.id === id))
      .map((id) => visible.find((v) => v.id === id)!)
      .map((b) => `<li><a href="${b.slug}.html">${esc(b.title)}</a></li>`)
      .join('');
    const meta = `<dl><dt>Type</dt><dd>${esc(String(n.meta.type || n.category))}</dd><dt>Status</dt><dd>${esc(String(n.meta.status || ''))}</dd><dt>Visibility</dt><dd>${esc(String(n.meta.visibility || 'private'))}</dd></dl>`;
    fs.writeFileSync(
      path.join(safeOut, 'notes', `${n.slug}.html`),
      page(
        n.title,
        `<article data-doc-id="${esc(n.id)}" data-doc-type="${esc(String(n.meta.type || n.category))}"><header><h1>${esc(n.title)}</h1>${meta}</header><section>${body}</section><aside><h2>Backlinks</h2><ul>${backlinks}</ul></aside></article>`,
      ),
    );
  }
  let cats = '';
  for (const [cat, items] of byCat as Map<string, Note[]>) {
    cats += `<section><h2><a href="${esc(cat)}.html">${esc(cat)}</a></h2><ul>${items.map((n) => `<li><a href="notes/${n.slug}.html">${esc(n.title)}</a></li>`).join('')}</ul></section>`;
    fs.writeFileSync(
      path.join(safeOut, `${cat}.html`),
      rootPage(cat, `<h1>${esc(cat)}</h1><ul>${items.map((n) => `<li><a href="notes/${n.slug}.html">${esc(n.title)}</a> <small>${esc(String(n.meta.status || ''))}</small></li>`).join('')}</ul>`),
    );
  }
  fs.writeFileSync(path.join(safeOut, 'index.html'), rootPage('Agent Memory Dashboard', `<h1>Agent Memory Dashboard</h1><p>${visible.length} notes generated in <strong>${mode}</strong> mode.</p>${cats}`));
  const chunks = visible.flatMap(chunkNote);
  fs.writeFileSync(path.join(safeOut, 'chunks.jsonl'), chunks.map((c) => JSON.stringify(c)).join('\n') + '\n');
  fs.writeFileSync(path.join(safeOut, 'search-index.json'), JSON.stringify(visible.map((n) => ({ id: n.id, title: n.title, path: `notes/${n.slug}.html`, category: n.category, tags: n.meta.tags || [], text: n.text.slice(0, 1000) })), null, 2));
  fs.writeFileSync(path.join(safeOut, 'manifest.json'), JSON.stringify({ generated_at: new Date().toISOString(), mode, count: visible.length, chunks: chunks.length, notes: visible.map((n) => ({ id: n.id, title: n.title, path: `notes/${n.slug}.html`, source: n.relPath })) }, null, 2));
  fs.writeFileSync(path.join(safeOut, 'assets', 'style.css'), css);
}

function groupBy<T>(arr: T[], fn: (x: T) => string) {
  const m = new Map<string, T[]>();
  for (const x of arr) {
    const k = fn(x);
    m.set(k, [...(m.get(k) || []), x]);
  }
  return m;
}

const css = `:root{color-scheme:light dark;--bg:#0b1020;--fg:#eef2ff;--muted:#9aa4bf;--card:#121a33;--link:#8bd3ff}body{margin:0;font:16px/1.6 system-ui;background:var(--bg);color:var(--fg)}header,footer{padding:1rem 2rem;background:#080c18}main{max-width:1100px;margin:auto;padding:2rem}a{color:var(--link)}section,article,aside{background:var(--card);border:1px solid #26314f;border-radius:16px;padding:1.25rem;margin:1rem 0}code,pre{background:#050814;border-radius:8px}pre{padding:1rem;overflow:auto}dl{display:grid;grid-template-columns:max-content 1fr;gap:.25rem 1rem;color:var(--muted)}`;
