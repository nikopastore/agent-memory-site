function esc(s: string): string {
  return String(s).replace(/[&<>"']/g, (c) =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!,
  );
}

function escAttr(s: string): string {
  return esc(s);
}

function safeMeta(meta: MemoryMeta, mode: BuildMode, strictRedact: boolean, deny: string[]): MemoryMeta {
  if (mode !== 'redacted') return meta;
  return redactDeep(meta, { strict: strictRedact, denyList: deny });
}

function safeNoteForMode(note: Note, options: BuildOptions): Note {
  const deny = denyListFor(note.meta);
  if (options.mode !== 'redacted') {
    // Even in non-redacted modes, surface a denyList if user opted in via frontmatter.
    if (deny.length === 0) return note;
    const opts = { denyList: deny, strict: options.strictRedact };
    return {
      ...note,
      title: redactText(note.title, opts),
      body: redactText(note.body, opts),
      html: redactText(note.html, opts),
      text: redactText(note.text, opts),
      meta: redactDeep(note.meta, opts),
    };
  }
  const opts = { strict: options.strictRedact, denyList: deny };
  return {
    ...note,
    title: redactText(note.title, opts),
    body: redactText(note.body, opts),
    html: redactText(note.html, opts),
    text: redactText(note.text, opts),
    meta: safeMeta(note.meta, options.mode, !!options.strictRedact, deny),
  };
}

const CSP =
  "default-src 'none'; style-src 'self' 'unsafe-inline'; img-src 'self' data: https:; script-src 'self'; connect-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";

interface PageContext {
  title: string;
  description?: string;
  basePath: string; // '' or '../' for /notes/*.html
  bodyMain: string;
  ogPath?: string;
  baseUrl?: string;
  siteTitle: string;
}

function page(ctx: PageContext): string {
  const base = ctx.basePath;
  const canonical = ctx.baseUrl && ctx.ogPath ? `${ctx.baseUrl.replace(/\/$/, '')}/${ctx.ogPath}` : undefined;
  const desc = ctx.description ? esc(ctx.description.slice(0, 200)) : esc(`${ctx.siteTitle} — semantic memory dashboard.`);
  const headLinks = [
    `<link rel="icon" href="${base}favicon.svg" type="image/svg+xml">`,
    `<link rel="stylesheet" href="${base}assets/style.css">`,
    canonical ? `<link rel="canonical" href="${esc(canonical)}">` : '',
  ]
    .filter(Boolean)
    .join('');
  const meta = [
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width,initial-scale=1">',
    `<meta http-equiv="Content-Security-Policy" content="${CSP}">`,
    '<meta name="referrer" content="no-referrer">',
    `<meta name="description" content="${desc}">`,
    `<meta name="generator" content="agent-memory-site ${esc(readVersion())}">`,
    '<meta property="og:type" content="website">',
    `<meta property="og:title" content="${esc(ctx.title)}">`,
    `<meta property="og:description" content="${desc}">`,
    canonical ? `<meta property="og:url" content="${esc(canonical)}">` : '',
    '<meta name="twitter:card" content="summary">',
    `<meta name="twitter:title" content="${esc(ctx.title)}">`,
    `<meta name="twitter:description" content="${desc}">`,
  ]
    .filter(Boolean)
    .join('');
  return `<!doctype html><html lang="en"><head>${meta}<title>${esc(ctx.title)}</title>${headLinks}</head><body><header data-index="false"><nav aria-label="Site"><a href="${base}index.html" class="brand">${esc(ctx.siteTitle)}</a><a href="${base}index.html">Dashboard</a><details><summary>Machine-readable</summary><a href="${base}search-index.json">search-index.json</a> · <a href="${base}manifest.json">manifest.json</a> · <a href="${base}chunks.jsonl">chunks.jsonl</a> · <a href="${base}llms.txt">llms.txt</a></details></nav></header><main>${ctx.bodyMain}</main><footer data-index="false">Generated by <a href="https://github.com/nikopastore/agent-memory-site">agent-memory-site</a> ${esc(readVersion())} · <a href="${base}llms.txt">llms.txt</a> · <a href="${base}AGENTS.md">AGENTS.md</a></footer><script src="${base}assets/search.js" defer></script><script src="${base}assets/copy.js" defer></script></body></html>`;
}

function categoryLabel(cat: string): string {
  return cat.charAt(0).toUpperCase() + cat.slice(1);
}

export function buildSite(notes: Note[], out: string, modeOrOptions: BuildMode | BuildOptions, opts: { force?: boolean } = {}): { out: string; chunks: number; notes: number } {
  const options: BuildOptions = typeof modeOrOptions === 'string' ? { mode: modeOrOptions } : modeOrOptions;
  const safeOut = assertSafeOutputDir(out, opts);
  const siteTitle = options.title || 'Agent Memory Dashboard';

  // Clean and recreate.
  fs.rmSync(safeOut, { recursive: true, force: true });
  fs.mkdirSync(path.join(safeOut, 'notes'), { recursive: true });
  fs.mkdirSync(path.join(safeOut, 'assets'), { recursive: true });

  // 1. Privacy filter.
  const visible = notes.filter((n) => includeNote(n, options.mode)).map((n) => safeNoteForMode(n, options));

  // 2. Build allowed wiki-link map (slug + slugified-title → href). Only visible notes!
  const allowed = new Map<string, string>();
  for (const n of visible) {
    allowed.set(n.id, `notes/${n.slug}.html`);
    allowed.set(n.slug, `notes/${n.slug}.html`);
    allowed.set(slugify(n.title), `notes/${n.slug}.html`);
  }

  // 3. Resolve wiki sentinels everywhere they could leak a hidden title:
  //    html (anchor form), body/text (plain-text label or [redacted-link]).
  const resolved = visible.map((n) => ({
    ...n,
    html: resolveWikiTokens(n.html, allowed),
    body: resolveWikiTokensText(n.body, allowed),
    text: resolveWikiTokensText(n.text, allowed),
  }));

  // 4. Categories.
  const byCat = groupBy(resolved, (n: Note) => n.category);

  // 5. Note pages.
  for (const n of resolved) {
    const backlinkItems = n.backlinks
      .map((id) => resolved.find((v) => v.id === id))
      .filter((b): b is Note => Boolean(b))
      .map((b) => `<li><a href="${esc(b.slug)}.html">${esc(b.title)}</a></li>`)
      .join('');
    const tagsHtml = Array.isArray(n.meta?.tags)
      ? (n.meta!.tags as unknown as string[]).map((t) => `<a class="tag" href="../${esc(String(t))}.html">${esc(String(t))}</a>`).join('')
      : '';
    const metaList = `<dl><dt>Type</dt><dd>${esc(String(n.meta?.type || n.category))}</dd><dt>Status</dt><dd>${esc(String(n.meta?.status || ''))}</dd><dt>Visibility</dt><dd>${esc(String(n.meta?.visibility || 'private'))}</dd>${n.updated_at ? `<dt>Updated</dt><dd>${esc(n.updated_at)}</dd>` : ''}</dl>`;
    const articleId = `article-${esc(n.slug)}`;
    const main = `<article id="${articleId}" data-doc-id="${esc(n.id)}" data-doc-type="${esc(String(n.meta?.type || n.category))}"><header><h1>${esc(n.title)} <button class="copy-btn" data-copy-target="#${articleId}" data-copy-format="markdown" type="button">Copy</button></h1>${metaList}${tagsHtml ? `<div>${tagsHtml}</div>` : ''}</header><section>${n.html}</section><aside aria-labelledby="bl-${esc(n.slug)}"><h2 id="bl-${esc(n.slug)}">Backlinks</h2>${backlinkItems ? `<ul>${backlinkItems}</ul>` : '<p class="empty">No backlinks.</p>'}</aside></article>`;
    fs.writeFileSync(
      path.join(safeOut, 'notes', `${n.slug}.html`),
      page({
        title: `${n.title} — ${siteTitle}`,
        description: n.text.slice(0, 160),
        basePath: '../',
        bodyMain: main,
        ogPath: `notes/${n.slug}.html`,
        baseUrl: options.baseUrl,
        siteTitle,
      }),
    );
  }

  // 6. Category pages.
  let cats = '';
  for (const [cat, items] of byCat as Map<string, Note[]>) {
    cats += `<section><h2><a href="${esc(cat)}.html">${esc(categoryLabel(cat))}</a> <small>(${items.length})</small></h2><ul class="note-list">${items
      .slice(0, 8)
      .map((n) => `<li><a href="notes/${esc(n.slug)}.html">${esc(n.title)}</a><small>${esc(String(n.meta?.status || ''))}</small></li>`)
      .join('')}</ul></section>`;
    fs.writeFileSync(
      path.join(safeOut, `${cat}.html`),
      page({
        title: `${categoryLabel(cat)} — ${siteTitle}`,
        description: `${items.length} ${cat} in ${siteTitle}.`,
        basePath: '',
        bodyMain: `<h1>${esc(categoryLabel(cat))}</h1><p class="cat-counts"><span>${items.length} notes</span></p><ul class="note-list">${items.map((n) => `<li><a href="notes/${esc(n.slug)}.html">${esc(n.title)}</a><small>${esc(String(n.meta?.status || ''))}</small></li>`).join('')}</ul>`,
        ogPath: `${cat}.html`,
        baseUrl: options.baseUrl,
        siteTitle,
      }),
    );
  }

  // 7. Dashboard.
  const countsHtml = [...byCat.entries()].map(([cat, items]) => `<a class="tag" href="${esc(cat)}.html">${esc(categoryLabel(cat))} <strong>${items.length}</strong></a>`).join('');
  const searchHtml = `<section class="search-wrap"><label for="search-input"><strong>Search</strong></label><input id="search-input" type="search" placeholder="Search titles, tags, content…" data-index="search-index.json" autocomplete="off"><div id="search-results" role="region" aria-live="polite"></div></section>`;
  fs.writeFileSync(
    path.join(safeOut, 'index.html'),
    page({
      title: siteTitle,
      description: `${resolved.length} notes generated in ${options.mode} mode.`,
      basePath: '',
      bodyMain: `<h1>${esc(siteTitle)}</h1><p>${resolved.length} notes · <strong>${options.mode}</strong> mode · generated ${new Date().toISOString().slice(0, 10)}</p><p class="cat-counts">${countsHtml || '<span>No categories</span>'}</p>${searchHtml}${cats}`,
      ogPath: 'index.html',
      baseUrl: options.baseUrl,
      siteTitle,
    }),
  );

  // 8. 404.
  fs.writeFileSync(
    path.join(safeOut, '404.html'),
    page({
      title: `Not found — ${siteTitle}`,
      description: 'Note not found.',
      basePath: '',
      bodyMain: NOT_FOUND_BODY,
      siteTitle,
    }),
  );

  // 9. Chunks.
  const allChunks = resolved.flatMap(chunkNote);
  // search-index: ALWAYS redact text + title (defense-in-depth), regardless of mode.
  const searchIndexEntries = resolved.map((n) => ({
    id: n.id,
    title: redactText(n.title, { strict: !!options.strictRedact, denyList: denyListFor(n.meta) }),
    path: `notes/${n.slug}.html`,
    category: n.category,
    tags: Array.isArray(n.meta?.tags) ? (n.meta!.tags as unknown as string[]).map((t) => redactText(String(t), { strict: !!options.strictRedact, denyList: denyListFor(n.meta) })) : [],
    text: redactText(n.text.slice(0, 1000), { strict: !!options.strictRedact, denyList: denyListFor(n.meta) }),
    updated: n.updated_at,
  }));

  fs.writeFileSync(path.join(safeOut, 'chunks.jsonl'), allChunks.map((c) => JSON.stringify(c)).join('\n') + (allChunks.length ? '\n' : ''));
  fs.writeFileSync(path.join(safeOut, 'search-index.json'), JSON.stringify(searchIndexEntries, null, 2));

  // Manifest: in public/redacted modes, drop the source file path (filenames are often codenames).
  const manifest = {
    generator: 'agent-memory-site',
    version: readVersion(),
    generated_at: new Date().toISOString(),
    mode: options.mode,
    title: siteTitle,
    count: resolved.length,
    chunks: allChunks.length,
    notes: resolved.map((n) => {
      const base: Record<string, unknown> = {
        id: n.id,
        title: n.title,
        path: `notes/${n.slug}.html`,
        category: n.category,
        updated: n.updated_at,
        content_hash: n.content_hash,
      };
      if (options.mode === 'private') base.source = n.relPath;
      return base;
    }),
  };
  fs.writeFileSync(path.join(safeOut, 'manifest.json'), JSON.stringify(manifest, null, 2));

  // 10. llms.txt + llms-full.txt + agent-card.json + AGENTS.md (T5.3 / T5.2 partial).
  writeLlmsTxt(safeOut, resolved, byCat, siteTitle, options);
  writeLlmsFull(safeOut, resolved);
  writeAgentCard(safeOut, resolved, siteTitle, options);
  writeAgentsMd(safeOut, resolved, siteTitle, options);

  // 11. Static assets.
  fs.writeFileSync(path.join(safeOut, 'assets', 'style.css'), CSS);
  fs.writeFileSync(path.join(safeOut, 'assets', 'search.js'), SEARCH_JS);
  fs.writeFileSync(path.join(safeOut, 'assets', 'copy.js'), COPY_JS);
  fs.writeFileSync(path.join(safeOut, 'favicon.svg'), FAVICON_SVG);

  // 12. Output marker (so future builds know it's safe to delete).
  writeMarker(safeOut, { mode: options.mode, count: resolved.length });

  return { out: safeOut, chunks: allChunks.length, notes: resolved.length };
}

function writeLlmsTxt(out: string, notes: Note[], byCat: Map<string, Note[]>, siteTitle: string, options: BuildOptions): void {
  const lines: string[] = [];
  lines.push(`# ${siteTitle}`);
  lines.push('');
  lines.push(options.description || `Semantic memory dashboard generated by agent-memory-site (${options.mode} mode).`);
  lines.push('');
  lines.push('## Retrieval artifacts');
  lines.push('- [chunks.jsonl](chunks.jsonl) — retrieval-ready chunks with provenance');
  lines.push('- [search-index.json](search-index.json) — keyword/metadata index');
  lines.push('- [manifest.json](manifest.json) — note inventory');
  lines.push('');
  for (const [cat, items] of byCat) {
    lines.push(`## ${categoryLabel(cat)}`);
    for (const n of items) {
      lines.push(`- [${n.title}](notes/${n.slug}.html)`);
    }
    lines.push('');
  }
  fs.writeFileSync(path.join(out, 'llms.txt'), lines.join('\n'));
}

function writeLlmsFull(out: string, notes: Note[]): void {
  const parts: string[] = [];
  for (const n of notes) {
    parts.push(`# ${n.title}`);
    parts.push(`<!-- doc_id: ${n.id} category: ${n.category} updated: ${n.updated_at || 'unknown'} -->`);
    parts.push('');
    parts.push(n.body);
    parts.push('');
    parts.push('---');
    parts.push('');
  }
  fs.writeFileSync(path.join(out, 'llms-full.txt'), parts.join('\n'));
}

function writeAgentCard(out: string, notes: Note[], siteTitle: string, options: BuildOptions): void {
  const dir = path.join(out, '.well-known');
  fs.mkdirSync(dir, { recursive: true });
  const card = {
    name: siteTitle,
    description: options.description || 'Semantic memory dashboard for AI agents.',
    version: readVersion(),
    capabilities: ['memory.search', 'memory.read'],
    artifacts: {
      chunks: 'chunks.jsonl',
      search_index: 'search-index.json',
      manifest: 'manifest.json',
      llms_txt: 'llms.txt',
      llms_full: 'llms-full.txt',
    },
    note_count: notes.length,
    generated_at: new Date().toISOString(),
    contact: undefined as string | undefined,
  };
  fs.writeFileSync(path.join(dir, 'agent-card.json'), JSON.stringify(card, null, 2));
}

function writeAgentsMd(out: string, notes: Note[], siteTitle: string, options: BuildOptions): void {
  const lines: string[] = [];
  lines.push(`# ${siteTitle} — AGENTS.md`);
  lines.push('');
  lines.push('> Generated automatically by agent-memory-site. This file gives any agent (Claude, Codex, Cursor, Copilot, Continue, Aider, etc.) a fast overview of the memory in this directory.');
  lines.push('');
  lines.push('## Retrieval');
  lines.push('- `chunks.jsonl` — RAG-ready chunks with provenance, stable content hashes, and visibility metadata');
  lines.push('- `search-index.json` — keyword index (text already redacted)');
  lines.push('- `manifest.json` — note inventory + counts');
  lines.push(`- Build mode: \`${options.mode}\``);
  lines.push('');
  lines.push('## Conventions');
  lines.push('- Each note has a stable `doc_id` (also the filename slug).');
  lines.push('- Wiki-link sentinels are resolved at build time and never leak titles from privacy-filtered notes.');
  lines.push('- All HTML is sandboxed by a strict CSP and a URL-scheme allowlist (no `javascript:` URLs).');
  lines.push('');
  lines.push(`## Note count: ${notes.length}`);
  fs.writeFileSync(path.join(out, 'AGENTS.md'), lines.join('\n'));
}

function groupBy<T>(arr: T[], fn: (x: T) => string): Map<string, T[]> {
  const m = new Map<string, T[]>();
  for (const x of arr) {
    const k = fn(x);
    m.set(k, [...(m.get(k) || []), x]);
  }
  return m;
}
